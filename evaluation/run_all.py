"""
run_all.py
----------
Runs the whole evaluation pipeline in dependency order and writes a
single Markdown report you can paste into the thesis.

Order matters and is not arbitrary:

  1. dataset    -- fixes the splits, so every later stage sees the same
                   train/val/test partition
  2. baselines  -- trains the classical reference systems and caches
                   their test predictions
  3. evaluate   -- scores the transformers, caches their logits, and
                   runs McNemar against those cached baseline predictions
  4. calibrate  -- fits temperature on validation using the cached logits
  5. selective  -- chooses tau against *calibrated* confidences, so it
                   must run after calibrate
  6. ood        -- sets the energy threshold
  7. benchmark  -- measures inference cost

Usage:
    python evaluation/run_all.py                    # everything
    python evaluation/run_all.py --skip baselines   # skip a slow stage
"""

import argparse
import json
import subprocess
import sys
from datetime import datetime
from pathlib import Path

# Deliberately no numpy, pandas, torch or sklearn imports here. This
# process stays alive for the whole run while each child loads a
# transformer, so every megabyte it holds is a megabyte the child cannot
# have. On a memory-constrained machine an orchestrator that imports the
# scientific stack is enough to push the children into allocation
# failure -- which PyTorch on Windows reports as an access violation
# rather than a MemoryError, making it look like a code bug.
EVAL_DIR = Path(__file__).resolve().parent
RESULTS_DIR = EVAL_DIR / "results"
STAGES = ["dataset", "baselines", "evaluate", "calibrate", "selective", "ood",
          "benchmark"]


def run_stage(name: str, csv_path: str | None) -> bool:
    script = EVAL_DIR / f"{name}.py"
    command = [sys.executable, str(script)]
    # Only the stages that read the corpus accept a CSV path argument.
    if csv_path and name in {"dataset", "baselines", "evaluate", "calibrate",
                             "selective", "ood"}:
        command.append(csv_path)

    # flush=True so the banner appears before the child's output even
    # when this process's stdout is redirected to a pipe or a log file,
    # where it would otherwise be block-buffered until exit.
    print("\n" + "=" * 74, flush=True)
    print(f"  STAGE: {name}", flush=True)
    print("=" * 74, flush=True)

    result = subprocess.run(command)
    if result.returncode != 0:
        print(f"\n  !! stage '{name}' failed with exit code {result.returncode}",
              flush=True)
        if result.returncode == 3221225477:
            print("     (Windows access violation — almost always memory exhaustion "
                  "while loading a model. Close other applications and retry; the "
                  "logit cache means completed stages will not be recomputed.)",
                  flush=True)
        return False
    return True


def _load(path: Path):
    if not path.exists():
        return None
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except (json.JSONDecodeError, OSError):
        return None


def write_report():
    """Assembles the per-stage JSON outputs into one Markdown summary."""
    transformer = _load(RESULTS_DIR / "transformer_metrics.json")
    baseline = _load(RESULTS_DIR / "baseline_metrics.json")
    calibration = _load(RESULTS_DIR / "calibration_metrics.json")
    selective = _load(RESULTS_DIR / "selective_metrics.json")
    ood = _load(RESULTS_DIR / "ood_metrics.json")

    lines = [
        "# UniFlow evaluation report",
        "",
        f"Generated {datetime.now().strftime('%Y-%m-%d %H:%M')}.",
        "",
    ]

    if transformer and transformer.get("leakage_risk"):
        lines += [
            "> **Methodological warning.** The train/validation/test split was "
            "generated by this pipeline rather than supplied by the training "
            "notebook. If the models were fine-tuned on rows now in the test set, "
            "these scores are inflated by data leakage. Resolve this before "
            "submission — see the guidance in `evaluation/dataset.py`.",
            "",
        ]

    # --- headline comparison -------------------------------------------
    lines += ["## 1. Classification performance", "",
              "| Task | System | Accuracy | Macro-F1 | Weighted-F1 |",
              "|---|---|---|---|---|"]
    for task in ("category", "urgency"):
        if baseline and task in baseline:
            for name, metrics in baseline[task].items():
                lines.append(
                    f"| {task} | {name} | {metrics['accuracy']:.4f} | "
                    f"{metrics['macro_f1']:.4f} | {metrics['weighted_f1']:.4f} |"
                )
        if transformer and task in transformer.get("tasks", {}):
            metrics = transformer["tasks"][task]
            backend = transformer.get("backend", "transformer")
            lines.append(
                f"| {task} | **{backend} transformer** | {metrics['accuracy']:.4f} | "
                f"**{metrics['macro_f1']:.4f}** | {metrics['weighted_f1']:.4f} |"
            )
            interval = metrics.get("macro_f1_ci") or {}
            if interval.get("ci_low") is not None:
                lines.append(
                    f"| {task} | _(transformer macro-F1 95% CI)_ | | "
                    f"[{interval['ci_low']:.4f}, {interval['ci_high']:.4f}] | |"
                )
    lines.append("")

    # --- significance ---------------------------------------------------
    if transformer:
        lines += ["## 2. Significance (McNemar exact test)", "",
                  "| Task | Baseline | Transformer only correct (b) | "
                  "Baseline only correct (c) | p | Verdict |",
                  "|---|---|---|---|---|---|"]
        for task, metrics in transformer.get("tasks", {}).items():
            for name, stat in (metrics.get("mcnemar") or {}).items():
                verdict = ("significant" if stat["significant_at_05"]
                           else "not significant")
                lines.append(
                    f"| {task} | {name} | {stat['b']} | {stat['c']} | "
                    f"{stat['p_value']:.4g} | {verdict} |"
                )
        lines.append("")

    # --- calibration ----------------------------------------------------
    if calibration:
        lines += ["## 3. Confidence calibration (temperature scaling)", "",
                  "| Task | T | ECE before | ECE after | NLL before | NLL after | "
                  "Mean conf. before | after |", "|---|---|---|---|---|---|---|---|"]
        for task, metrics in calibration.items():
            before, after = metrics["before"], metrics["after"]
            lines.append(
                f"| {task} | {metrics['temperature']:.3f} | {before['ece']:.4f} | "
                f"{after['ece']:.4f} | {before['nll']:.4f} | {after['nll']:.4f} | "
                f"{before['mean_confidence']:.3f} | {after['mean_confidence']:.3f} |"
            )
        lines += ["",
                  "Accuracy is unchanged by temperature scaling by construction; "
                  "only the reported confidences move. See "
                  "`reliability_category.png` and `reliability_urgency.png`.", ""]

    # --- selective prediction -------------------------------------------
    if selective:
        lines += ["## 4. Selective routing (risk–coverage)", "",
                  "| Task | τ | Coverage | Selective risk | Risk if fully automated | "
                  "Misroutes avoided | AURC |", "|---|---|---|---|---|---|---|"]
        for task, metrics in selective.items():
            point = metrics["test_operating_point"]
            if point.get("risk") is None:
                continue
            lines.append(
                f"| {task} | {point['tau']:.3f} | {point['coverage']:.1%} | "
                f"{point['risk']:.2%} | {point['full_coverage_risk']:.2%} | "
                f"{point['errors_prevented']} | {metrics['aurc_test']:.4f} |"
            )
        lines += ["",
                  "τ is selected on the validation split against a target selective "
                  "risk and then applied unchanged to the test split.", ""]

    # --- OOD -------------------------------------------------------------
    if ood:
        lines += ["## 5. Out-of-scope detection (energy score)", "",
                  f"- AUROC: **{ood['auroc']:.4f}**",
                  f"- FPR at {ood['target_tpr']:.0%} TPR: {ood['fpr_at_tpr']:.4f}",
                  f"- Energy threshold: {ood['threshold']:.4f}",
                  f"- Out-of-scope messages caught: {ood['ood_detection_rate']:.1%}",
                  f"- Genuine inquiries diverted to Triage: "
                  f"{ood['in_distribution_diverted']:.1%}",
                  f"- Probe set: {ood['n_probe']} items"
                  + (" (**synthetic** — replace with real out-of-scope mail)"
                     if ood["probe_set_synthetic"] else ""),
                  ""]

    # --- cost -------------------------------------------------------------
    rows = []
    for backend in ("dual", "multitask"):
        record = _load(RESULTS_DIR / f"benchmark_{backend}.json")
        if record:
            rows.append(record)
    if rows:
        lines += ["## 6. Inference cost", "",
                  "| Backend | Params (M) | Disk (MB) | Forward passes | "
                  "Median latency (ms) | p95 (ms) |", "|---|---|---|---|---|---|"]
        for record in rows:
            lines.append(
                f"| {record['backend']} | {record['parameters_millions']:.2f} | "
                f"{record['disk_mb']:.1f} | "
                f"{record['forward_passes_per_inquiry']} | "
                f"{record['latency']['median_ms']:.1f} | "
                f"{record['latency']['p95_ms']:.1f} |"
            )
        lines += ["", f"Measured on {rows[0]['device']}, "
                      f"{rows[0]['torch_threads']} threads, {rows[0]['platform']}.", ""]

    lines += ["## Figures", "",
              "All figures are in `evaluation/results/`:", "",
              "- `confusion_category.png`, `confusion_urgency.png`",
              "- `reliability_category.png`, `reliability_urgency.png`",
              "- `risk_coverage_category.png`, `risk_coverage_urgency.png`",
              "- `ood_energy.png`", ""]

    report_path = RESULTS_DIR / "REPORT.md"
    report_path.write_text("\n".join(lines), encoding="utf-8")
    return report_path


def main():
    parser = argparse.ArgumentParser(description="Run the full evaluation pipeline")
    parser.add_argument("csv", nargs="?", default=None,
                        help="path to the labelled dataset CSV")
    parser.add_argument("--skip", nargs="*", default=[], choices=STAGES,
                        help="stages to skip")
    parser.add_argument("--only", nargs="*", default=None, choices=STAGES,
                        help="run only these stages")
    args = parser.parse_args()

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    stages = args.only if args.only else [s for s in STAGES if s not in args.skip]

    failed = []
    for stage in stages:
        if not run_stage(stage, args.csv):
            failed.append(stage)

    report_path = write_report()
    print("\n" + "=" * 74)
    if failed:
        print(f"  Completed with failures in: {', '.join(failed)}")
    else:
        print("  All stages completed.")
    print(f"  Report: {report_path}")
    print("=" * 74)


if __name__ == "__main__":
    main()
