"""
base.py
-------
The declarative base and the portable column types.

The same models must run on SQLite (tests, local development) and on
PostgreSQL (deployment) without a second set of definitions, so three
types are wrapped here:

  UtcDateTime  Always stores UTC and always returns a timezone-aware
               datetime. SQLite has no native timezone handling, and the
               old schema stored every timestamp as a naive local ISO
               *string* -- which made every window query a string
               comparison and every duration silently wrong across a DST
               boundary.
  JSONColumn   JSONB on PostgreSQL, JSON elsewhere.
  BigPK        BIGSERIAL on PostgreSQL, INTEGER on SQLite (which only
               auto-increments an INTEGER primary key).
"""

from __future__ import annotations

from datetime import datetime, timezone

import sqlalchemy as sa
from sqlalchemy.dialects import postgresql
from sqlalchemy.orm import DeclarativeBase


class UtcDateTime(sa.types.TypeDecorator):
    """A timezone-aware DateTime that is UTC on both sides of the wire."""

    impl = sa.DateTime(timezone=True)
    cache_ok = True

    def process_bind_param(self, value, dialect):
        if value is None:
            return None
        if not isinstance(value, datetime):
            raise TypeError(f"expected datetime, got {type(value).__name__}")
        if value.tzinfo is None:
            # A naive datetime reaching the database is a bug, but assuming
            # UTC is safer than letting the driver guess local time.
            value = value.replace(tzinfo=timezone.utc)
        return value.astimezone(timezone.utc)

    def process_result_value(self, value, dialect):
        if value is None:
            return None
        if value.tzinfo is None:
            return value.replace(tzinfo=timezone.utc)
        return value.astimezone(timezone.utc)


JSONColumn = sa.JSON().with_variant(postgresql.JSONB, "postgresql")
BigInt = sa.BigInteger().with_variant(sa.Integer, "sqlite")
SmallInt = sa.SmallInteger().with_variant(sa.Integer, "sqlite")


def enum_column(python_enum, name: str) -> sa.Enum:
    """A native ENUM on PostgreSQL, VARCHAR + CHECK constraint elsewhere.

    values_callable makes SQLAlchemy persist the enum *value* ("In Progress")
    rather than its member name ("IN_PROGRESS"), which keeps stored data
    readable and matches what the old free-text columns held.
    """
    return sa.Enum(
        python_enum,
        name=name,
        native_enum=True,
        values_callable=lambda enum_cls: [member.value for member in enum_cls],
        validate_strings=True,
    )


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


# Deterministic constraint names, so a CHECK or UNIQUE violation names the
# actual rule in its error message instead of SQLite's or PostgreSQL's
# autogenerated identifier. Has to be handed to MetaData at construction:
# the convention is consulted as each constraint is attached to a table.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_name)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = sa.MetaData(naming_convention=NAMING_CONVENTION)

    type_annotation_map = {
        datetime: UtcDateTime,
        dict: JSONColumn,
        list: JSONColumn,
    }

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        pk = getattr(self, "id", None)
        return f"<{type(self).__name__} id={pk}>"
